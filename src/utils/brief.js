// Builds a one-page HTML market brief from the /rank response (opens in any browser, prints to PDF).
// Only shows values the API returned — nothing is calculated here.

const esc = (s) =>
  String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

export function downloadBrief({ result, selected, product, basedIn, lensText, channelLabel }) {
  if (!result?.ranked?.length) return;
  const top3 = result.ranked.slice(0, 3);
  const focus = selected || top3[0];
  const today = new Date().toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric" });

  const card = (r) => `
    <div class="mk">
      <div class="rk">${esc(r.rank)}</div>
      <div class="bd">
        <h3>${esc(r.name)} · ${esc(r.segment)} · ${esc(channelLabel(r.channel))}</h3>
        <p>Demand ${esc(r.scores?.demand)} · Health need ${esc(r.scores?.health)} · Meat cost ${esc(r.scores?.affordability)}.
           ${esc(r.capacity?.slots_left)} of ${esc(r.capacity?.capacity)} slots left.</p>
        <p class="t"><b>Test:</b> ${esc(r.explanation?.test_first)}</p>
      </div>
      <div class="sc"><b>${esc(r.scores?.total)}</b><small>range ${esc(r.scores?.low)}–${esc(r.scores?.high)}</small><small>${esc(r.confidence?.pct)}% confidence</small></div>
    </div>`;

  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>MarketLens brief · ${esc(focus.name)}</title>
<style>
  body{font-family:Inter,Arial,sans-serif;color:#17201b;max-width:760px;margin:32px auto;padding:0 24px;line-height:1.45}
  h1{font-size:22px;margin:4px 0}h2{font-size:12px;letter-spacing:.08em;color:#5d6b63;margin:26px 0 10px}
  .top{display:flex;justify-content:space-between;font-size:12px;color:#5d6b63}
  .mk{display:flex;gap:14px;border:1px solid #DDE3DE;border-radius:12px;padding:14px;margin-bottom:10px}
  .rk{width:32px;height:32px;border-radius:50%;background:#1B7F4C;color:#fff;display:grid;place-items:center;font-weight:700;flex:none}
  .bd{flex:1}.bd h3{margin:0 0 4px;font-size:15px}.bd p{margin:2px 0;font-size:13px}.t{color:#1B7F4C}
  .sc{text-align:right;min-width:110px}.sc b{font-size:26px;display:block}.sc small{display:block;color:#5d6b63;font-size:11px}
  .two{display:grid;grid-template-columns:1fr 1fr;gap:20px}.row{display:flex;justify-content:space-between;border-bottom:1px solid #eef1ee;padding:6px 0;font-size:13px}
  ul{margin:0;padding-left:18px;font-size:13px}.foot{margin-top:28px;font-size:11px;color:#5d6b63;display:flex;justify-content:space-between}
</style></head><body>
<div class="top"><span>MARKETLENS · MARKET BRIEF</span><span>Generated ${esc(today)} · Data as of ${esc(result.meta?.data_as_of)}</span></div>
<h1>${esc(product?.name || "Your product")}</h1>
<div style="font-size:13px;color:#5d6b63">${esc((product?.uses || []).join(", "))} · Health lens: ${esc(lensText)}${basedIn ? ` · Based in ${esc(basedIn)}` : ""}</div>
<h2>TOP 3 MARKETS TO TEST FIRST</h2>
${top3.map(card).join("")}
<div class="two">
  <div><h2>THE 3 CHECKS FOR ${esc(String(focus.name).toUpperCase())}</h2>
    <div class="row"><span>Demand</span><b>${esc(focus.scores?.demand)}</b></div>
    <div class="row"><span>Health need</span><b>${esc(focus.scores?.health)}</b></div>
    <div class="row"><span>Meat cost</span><b>${esc(focus.scores?.affordability)}</b></div>
  </div>
  <div><h2>ASSUMPTIONS TO CHECK</h2><ul>
    <li>${esc(focus.explanation?.uncertain)}</li>
    <li>Demand label: ${esc(focus.labels?.demand)}; health label: ${esc(focus.labels?.health)}; meat-cost label: ${esc(focus.labels?.affordability)}.</li>
  </ul></div>
</div>
<h2>HOW TO READ THIS</h2>
<p style="font-size:13px">Scores (0–100) rank places against each other; they are not sales forecasts. Each place is scored on demand,
health need and meat cost. Health data is context, not proof of demand, and no product claims to prevent disease.
Confidence comes from ${esc(result.meta?.n_simulations)} simulations (seed ${esc(result.meta?.seed)}). Run the suggested test before committing stock.</p>
<div class="foot"><span>Generated by MarketLens · Hack the Fork Nigeria 2026</span><span>Sources listed in the app's Evidence tab</span></div>
</body></html>`;

  const url = URL.createObjectURL(new Blob([html], { type: "text/html" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = `MarketLens-brief-${String(focus.name).replace(/\s+/g, "-")}.html`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}